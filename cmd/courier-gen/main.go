// courier-gen adds typed async clients and registration helpers to official
// Apache Thrift 0.25.0 Go output. It never parses IDL or edits that output.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const compilerHeader = "Code generated by Thrift Compiler (0.25.0)."

func main() {
	input := flag.String("in", "", "official Thrift-generated Go source")
	output := flag.String("out", "", "async Go output (must differ from input)")
	core := flag.String("runtime", "github.com/nextpkg/courier", "Courier runtime module path")
	flag.Parse()
	if err := run(*input, *output, *core); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func run(input, output, core string) error {
	if input == "" || output == "" {
		return fmt.Errorf("courier-gen: -in and -out required")
	}
	a, _ := filepath.Abs(input)
	b, _ := filepath.Abs(output)
	if a == b {
		return fmt.Errorf("courier-gen: cannot overwrite official source")
	}
	data, err := os.ReadFile(input)
	if err != nil {
		return err
	}
	generated, err := generate(data, core)
	if err != nil {
		return err
	}
	return os.WriteFile(output, generated, 0644)
}
func render(n any) string {
	var b bytes.Buffer
	_ = printer.Fprint(&b, token.NewFileSet(), n)
	return b.String()
}
func ident(e ast.Expr) string {
	v, _ := e.(*ast.Ident)
	if v == nil {
		return ""
	}
	return v.Name
}
func receiver(fn *ast.FuncDecl) string {
	if fn.Recv == nil || len(fn.Recv.List) != 1 {
		return ""
	}
	p, ok := fn.Recv.List[0].Type.(*ast.StarExpr)
	if !ok {
		return ""
	}
	return ident(p.X)
}
func thriftCall(s ast.Stmt) (*ast.CallExpr, bool) {
	a, ok := s.(*ast.AssignStmt)
	if !ok || len(a.Rhs) != 1 {
		return nil, false
	}
	c, ok := a.Rhs[0].(*ast.CallExpr)
	if !ok {
		return nil, false
	}
	sel, ok := c.Fun.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != "Call" {
		return nil, false
	}
	inner, ok := sel.X.(*ast.CallExpr)
	if !ok {
		return nil, false
	}
	getter, ok := inner.Fun.(*ast.SelectorExpr)
	return c, ok && getter.Sel.Name == "Client_"
}
func generate(data []byte, core string) ([]byte, error) {
	if !bytes.Contains(data, []byte(compilerHeader)) {
		return nil, fmt.Errorf("courier-gen: expected official Thrift compiler 0.25.0 output; validate new compiler before changing this guard")
	}
	f, err := parser.ParseFile(token.NewFileSet(), "thrift.go", data, 0)
	if err != nil {
		return nil, err
	}
	byService := map[string][]*ast.FuncDecl{}
	for _, d := range f.Decls {
		fn, ok := d.(*ast.FuncDecl)
		if !ok || fn.Body == nil {
			continue
		}
		r := receiver(fn)
		if !strings.HasSuffix(r, "Client") {
			continue
		}
		for _, s := range fn.Body.List {
			if _, ok := thriftCall(s); ok {
				byService[strings.TrimSuffix(r, "Client")] = append(byService[strings.TrimSuffix(r, "Client")], fn)
				break
			}
		}
	}
	if len(byService) == 0 {
		return nil, fmt.Errorf("courier-gen: no supported unary services found")
	}
	// Fail explicitly rather than silently dropping inherited methods.
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, sp := range g.Specs {
			t, ok := sp.(*ast.TypeSpec)
			if !ok {
				continue
			}
			it, ok := t.Type.(*ast.InterfaceType)
			if !ok {
				continue
			}
			for _, field := range it.Methods.List {
				if len(field.Names) == 0 {
					return nil, fmt.Errorf("courier-gen: service inheritance is not supported: %s", t.Name)
				}
			}
		}
	}
	names := make([]string, 0, len(byService))
	for n := range byService {
		names = append(names, n)
	}
	sort.Strings(names)
	var body strings.Builder
	for _, name := range names {
		for _, helper := range []string{"Dial" + name, "Listen" + name} {
			if f.Scope.Lookup(helper) != nil {
				return nil, fmt.Errorf("courier-gen: generated helper name collision: %s", helper)
			}
		}
		methodNames := map[string]bool{}
		for _, fn := range byService[name] {
			for _, n := range []string{fn.Name.Name, fn.Name.Name + "Async"} {
				if methodNames[n] {
					return nil, fmt.Errorf("courier-gen: generated method name collision: %s.%s", name, n)
				}
				methodNames[n] = true
			}
		}
		if err := renderTemplate(&body, "service.go.tmpl", serviceTemplateData{Name: name}); err != nil {
			return nil, err
		}
		for _, fn := range byService[name] {
			m, err := method(name, fn)
			if err != nil {
				return nil, err
			}
			body.WriteString(m)
		}
	}
	// Copy only imports actually referenced by the new AST (including IDL includes).
	fragment, err := parser.ParseFile(token.NewFileSet(), "async.go", "package "+f.Name.Name+"\n"+body.String(), 0)
	if err != nil {
		return nil, fmt.Errorf("courier-gen: generated syntax: %w", err)
	}
	qualifiers := map[string]bool{}
	ast.Inspect(fragment, func(n ast.Node) bool {
		if s, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := s.X.(*ast.Ident); ok {
				qualifiers[id.Name] = true
			}
		}
		return true
	})
	imports := map[string]string{"courier": core, "context": "context", "fmt": "fmt"}
	for _, sp := range f.Imports {
		p, _ := strconv.Unquote(sp.Path.Value)
		alias := filepath.Base(p)
		if sp.Name != nil {
			alias = sp.Name.Name
		}
		if qualifiers[alias] {
			if expected, reserved := imports[alias]; reserved && p != expected {
				return nil, fmt.Errorf("courier-gen: reserved import alias %s", alias)
			}
			imports[alias] = p
		}
	}
	aliases := make([]string, 0, len(imports))
	for a := range imports {
		aliases = append(aliases, a)
	}
	sort.Strings(aliases)
	fileData := fileTemplateData{Package: f.Name.Name, Body: body.String()}
	for _, a := range aliases {
		fileData.Imports = append(fileData.Imports, importTemplateData{Alias: a, Path: imports[a]})
	}
	var out strings.Builder
	if err := renderTemplate(&out, "file.go.tmpl", fileData); err != nil {
		return nil, err
	}
	return format.Source([]byte(out.String()))
}
func method(service string, fn *ast.FuncDecl) (string, error) {
	fail := func(msg string) (string, error) {
		return "", fmt.Errorf("courier-gen: %s.%s: %s", service, fn.Name, msg)
	}
	var call *ast.CallExpr
	index := -1
	for i, s := range fn.Body.List {
		if c, ok := thriftCall(s); ok {
			call = c
			index = i
			break
		}
	}
	if call == nil || len(call.Args) != 4 {
		return fail("unsupported generated Call shape")
	}
	if ident(call.Args[3]) == "nil" {
		return fail("oneway is outside unary request/response scope")
	}
	if fn.Type.Results == nil || len(fn.Type.Results.List) < 1 || len(fn.Type.Results.List) > 2 {
		return fail("unsupported result shape")
	}
	isVoid := len(fn.Type.Results.List) == 1
	valueType := "struct{}"
	resultSig := "(_r struct{}, _err error)"
	if !isVoid {
		valueType = render(fn.Type.Results.List[0].Type)
		resultSig = render(fn.Type.Results)
	}
	// FieldList printing alone omits parentheses. Render a FuncType instead.
	signature := render(&ast.FuncType{Params: fn.Type.Params})
	params := strings.TrimPrefix(signature, "func")
	if !isVoid {
		resultSig = strings.TrimPrefix(render(&ast.FuncType{Params: &ast.FieldList{}, Results: fn.Type.Results}), "func()")
	}
	ctxName := render(call.Args[0])
	recv := "_courierClient"
	used := map[string]bool{}
	ast.Inspect(fn, func(n ast.Node) bool {
		if id, ok := n.(*ast.Ident); ok {
			used[id.Name] = true
		}
		return true
	})
	fresh := func(name string) string {
		for used[name] {
			name += "_"
		}
		used[name] = true
		return name
	}
	recv = fresh(recv)
	futureName, errorName, zeroName := fresh("f"), fresh("err"), fresh("zero")
	if index+3 >= len(fn.Body.List) {
		return fail("missing result unwrapping")
	}
	// Pin the small extension seam to the compiler version and structure.
	meta, ok := fn.Body.List[index+1].(*ast.ExprStmt)
	if !ok || !strings.Contains(render(meta), "SetLastResponseMeta_(") {
		return fail("unsupported metadata statement")
	}
	gate, ok := fn.Body.List[index+2].(*ast.IfStmt)
	if !ok || render(gate.Cond) != "_err != nil" {
		return fail("unsupported error gate")
	}
	var setup strings.Builder
	for _, s := range fn.Body.List[:index] {
		if d, ok := s.(*ast.DeclStmt); ok {
			if g, ok := d.Decl.(*ast.GenDecl); ok && len(g.Specs) == 1 {
				if v, ok := g.Specs[0].(*ast.ValueSpec); ok && v.Type != nil && render(v.Type) == "thrift.ResponseMeta" {
					continue
				}
			}
		}
		setup.WriteString(render(s))
		setup.WriteByte('\n')
	}
	tail := fn.Body.List[index+3:]
	if isVoid {
		// Official void result returns only error; adapt every return into (unit,error).
		for _, s := range tail {
			ast.Inspect(s, func(n ast.Node) bool {
				if r, ok := n.(*ast.ReturnStmt); ok {
					if len(r.Results) == 0 {
						r.Results = []ast.Expr{&ast.CompositeLit{Type: &ast.StructType{Fields: &ast.FieldList{}}}, ast.NewIdent("_err")}
					} else if len(r.Results) == 1 {
						r.Results = append([]ast.Expr{&ast.CompositeLit{Type: &ast.StructType{Fields: &ast.FieldList{}}}}, r.Results...)
					}
				}
				return true
			})
		}
	}
	var unwrap strings.Builder
	for _, s := range tail {
		unwrap.WriteString(render(s))
		unwrap.WriteByte('\n')
	}
	args := []string{}
	for _, p := range fn.Type.Params.List {
		for _, n := range p.Names {
			args = append(args, n.Name)
		}
	}
	data := methodTemplateData{
		Receiver: recv, Service: service, Name: fn.Name.Name,
		Params: params, ValueType: valueType, ResultSignature: resultSig,
		Setup: setup.String(), Unwrap: unwrap.String(), Context: ctxName,
		WireMethod: render(call.Args[1]), Request: render(call.Args[2]), Response: render(call.Args[3]),
		Arguments: strings.Join(args, ","), Void: isVoid,
		Future: futureName, Error: errorName, Zero: zeroName,
	}
	var b strings.Builder
	if err := renderTemplate(&b, "method.go.tmpl", data); err != nil {
		return "", err
	}
	return b.String(), nil
}
